#!/usr/bin/env node
// Fetches the current stable browser versions and writes versions.js.
// Run: node scripts/update-ua.mjs   (Node 18+, no dependencies)
import { writeFile } from 'node:fs/promises';

const get = async (url) => {
  const res = await fetch(url, { headers: { 'user-agent': 'rrandom-version-updater' } });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return res.json();
};
const cmp = (a, b) => {
  const x = a.split('.').map(Number), y = b.split('.').map(Number);
  for (let i = 0; i < Math.max(x.length, y.length); i++) if ((x[i] || 0) !== (y[i] || 0)) return (x[i] || 0) - (y[i] || 0);
  return 0;
};

const out = { updated: new Date().toISOString().slice(0, 10) };

try {
  const d = await get('https://versionhistory.googleapis.com/v1/chrome/platforms/win/channels/stable/versions');
  out.chrome = d.versions.map((v) => v.version).sort(cmp).pop();
} catch (e) { console.warn('chrome:', e.message); }

try {
  const d = await get('https://product-details.mozilla.org/1.0/firefox_versions.json');
  out.firefox = d.LATEST_FIREFOX_VERSION;
} catch (e) { console.warn('firefox:', e.message); }

try {
  const d = await get('https://edgeupdates.microsoft.com/api/products');
  const stable = d.find((p) => p.Product === 'Stable');
  out.edge = stable.Releases.filter((r) => r.Platform === 'Windows').map((r) => r.ProductVersion).sort(cmp).pop();
} catch (e) { console.warn('edge:', e.message); }

// Safari has no public version feed. Apple ships a new major each September
// (Safari 26 in Sep 2025) and a point release roughly every two months.
{
  const now = new Date();
  const y = now.getUTCFullYear(), m = now.getUTCMonth() + 1;
  const major = m >= 9 ? y - 1999 : y - 2000;
  const monthsIn = m >= 9 ? m - 9 : m + 3;
  out.safari = `${major}.${Math.min(6, Math.floor(monthsIn / 2))}`;
}

// All or nothing: a partial file would make the page build UAs from missing versions.
const failed = ['chrome', 'firefox', 'edge'].filter((k) => !/^\d+(\.\d+)+$/.test(out[k] || ''));
if (failed.length) {
  console.error(`Not writing versions.js: could not fetch ${failed.join(', ')}. The existing file is unchanged.`);
  process.exit(1);
}

const body = `/* Generated by scripts/update-ua.mjs. Do not edit by hand. */\nwindow.RR_UA = ${JSON.stringify(out, null, 2)};\n`;
const target = new URL('../versions.js', import.meta.url);
await writeFile(target, body);
console.log('Wrote versions.js', out);
